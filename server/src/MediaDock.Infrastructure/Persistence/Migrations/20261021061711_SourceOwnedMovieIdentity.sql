            OR NULLIF(btrim(title.poster_url), '') IS NOT NULL OR NULLIF(btrim(title.runtime), '') IS NOT NULL
            OR NULLIF(btrim(title.awards), '') IS NOT NULL OR NULLIF(btrim(title.box_office), '') IS NOT NULL);

        RAISE NOTICE 'Source-owned movie migration will delete % non-transferable favorite rows', discard_favorite_count;
        RAISE NOTICE 'Source-owned movie migration will not copy legacy fallback metadata from % titles', fallback_title_count;
